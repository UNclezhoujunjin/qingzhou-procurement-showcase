CREATE TABLE app_user (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username VARCHAR(64) NOT NULL UNIQUE,
  password_hash VARCHAR(100) NOT NULL,
  display_name VARCHAR(64) NOT NULL,
  department VARCHAR(64) NOT NULL,
  role VARCHAR(24) NOT NULL CHECK (role IN ('ADMIN','EMPLOYEE','MANAGER','BUYER','WAREHOUSE'))
);
CREATE TABLE supplier (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(120) NOT NULL UNIQUE,
  contact VARCHAR(64) NOT NULL,
  phone VARCHAR(32) NOT NULL
);
CREATE TABLE product (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sku VARCHAR(40) NOT NULL UNIQUE,
  name VARCHAR(120) NOT NULL,
  category VARCHAR(40) NOT NULL,
  unit VARCHAR(16) NOT NULL,
  price DECIMAL(14,2) NOT NULL CHECK (price > 0),
  min_stock INTEGER NOT NULL CHECK (min_stock >= 0),
  stock INTEGER NOT NULL DEFAULT 0 CHECK (stock >= 0),
  supplier_id BIGINT NOT NULL REFERENCES supplier(id)
);
CREATE TABLE purchase_request (
  id VARCHAR(36) PRIMARY KEY,
  number VARCHAR(40) NOT NULL UNIQUE,
  applicant_id BIGINT NOT NULL REFERENCES app_user(id),
  product_id BIGINT NOT NULL REFERENCES product(id),
  quantity INTEGER NOT NULL CHECK (quantity BETWEEN 1 AND 100000),
  unit_price DECIMAL(14,2) NOT NULL,
  reason VARCHAR(500) NOT NULL,
  status VARCHAR(24) NOT NULL CHECK (status IN ('PENDING','APPROVED','REJECTED','ORDERED','RECEIVED')),
  review_note VARCHAR(500),
  reviewer_id BIGINT REFERENCES app_user(id),
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE purchase_order (
  id VARCHAR(36) PRIMARY KEY,
  number VARCHAR(40) NOT NULL UNIQUE,
  request_id VARCHAR(36) NOT NULL UNIQUE REFERENCES purchase_request(id),
  supplier_id BIGINT NOT NULL REFERENCES supplier(id),
  status VARCHAR(24) NOT NULL CHECK (status IN ('OPEN','RECEIVED')),
  buyer_id BIGINT NOT NULL REFERENCES app_user(id),
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  received_at TIMESTAMP
);
CREATE TABLE stock_movement (
  id VARCHAR(36) PRIMARY KEY,
  product_id BIGINT NOT NULL REFERENCES product(id),
  type VARCHAR(16) NOT NULL CHECK (type IN ('OPENING','IN','OUT')),
  quantity INTEGER NOT NULL CHECK (quantity <> 0),
  balance INTEGER NOT NULL CHECK (balance >= 0),
  reference VARCHAR(100) NOT NULL,
  operator_id BIGINT NOT NULL REFERENCES app_user(id),
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE idempotency_record (
  actor_id BIGINT NOT NULL REFERENCES app_user(id),
  operation VARCHAR(40) NOT NULL,
  request_key VARCHAR(80) NOT NULL,
  fingerprint VARCHAR(64) NOT NULL,
  resource_id VARCHAR(36) NOT NULL,
  PRIMARY KEY (actor_id, operation, request_key)
);
CREATE TABLE audit_log (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_id BIGINT NOT NULL REFERENCES app_user(id),
  action VARCHAR(80) NOT NULL,
  target VARCHAR(120) NOT NULL,
  detail VARCHAR(500) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_request_applicant ON purchase_request(applicant_id, created_at);
CREATE INDEX idx_request_status ON purchase_request(status);
CREATE INDEX idx_movement_product ON stock_movement(product_id, created_at);
CREATE INDEX idx_audit_time ON audit_log(created_at);
