package com.qingzhou.procurement;

import java.nio.file.*;
import java.util.zip.ZipFile;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;
import static org.junit.jupiter.api.Assertions.*;

class BackupRecoveryTest {
    @TempDir(factory=ProjectTempFactory.class) Path temp;
    static class ProjectTempFactory implements org.junit.jupiter.api.io.TempDirFactory {
        @Override public Path createTempDirectory(org.junit.jupiter.api.extension.AnnotatedElementContext element,org.junit.jupiter.api.extension.ExtensionContext context)throws java.io.IOException {
            Path parent=Path.of("target","backup-test-tmp").toAbsolutePath();Files.createDirectories(parent);return Files.createTempDirectory(parent,"run-");
        }
    }
    @Test void onlineBackupRestoresAnEarlierConsistentSnapshot()throws Exception {
        String options=";MODE=PostgreSQL;DATABASE_TO_LOWER=TRUE;DEFAULT_NULL_ORDERING=HIGH";
        var db=new JdbcTemplate(new DriverManagerDataSource("jdbc:h2:file:"+temp.resolve("original/qingzhou")+options,"sa",""));
        db.execute("CREATE TABLE app_user(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY)");
        for(String table:java.util.List.of("product","purchase_request","stock_movement"))db.execute("CREATE TABLE "+table+"(id INTEGER PRIMARY KEY)");
        db.execute("CREATE TABLE probe(id INTEGER PRIMARY KEY,quantity INTEGER NOT NULL)");db.update("INSERT INTO probe VALUES(1,12)");
        var service=new BackupService(db,temp.resolve("backups").toString());var backup=service.create();String name=backup.get("name").toString();
        assertEquals(true,service.verify(name).get("valid"));db.update("UPDATE probe SET quantity=99");
        Path restored=temp.resolve("restored/qingzhou.mv.db");Files.createDirectories(restored.getParent());
        try(var zip=new ZipFile(service.file(name).toFile())) {
            var entry=zip.stream().filter(e->e.getName().replace('\\','/').endsWith("qingzhou.mv.db")).findFirst().orElseThrow();
            try(var stream=zip.getInputStream(entry)){Files.copy(stream,restored);}
        }
        BackupProbe.verify(temp.resolve("restored/qingzhou").toString(),"sa","");
        var recovery=new JdbcTemplate(new DriverManagerDataSource("jdbc:h2:file:"+temp.resolve("restored/qingzhou")+options,"sa",""));
        assertEquals(12,recovery.queryForObject("SELECT quantity FROM probe WHERE id=1",Integer.class));
        assertEquals(99,db.queryForObject("SELECT quantity FROM probe WHERE id=1",Integer.class));
        Files.write(service.file(name),new byte[]{1},StandardOpenOption.APPEND);assertEquals(false,service.verify(name).get("valid"));
        assertThrows(BusinessError.class,()->service.file("../qingzhou.mv.db"));
    }
    @Test void inMemoryDatabasesCannotPretendToProducePersistentBackups(){var service=new BackupService(new JdbcTemplate(new DriverManagerDataSource("jdbc:h2:mem:backup-test","sa","")),temp.toString());assertEquals(409,assertThrows(BusinessError.class,service::create).status);}
}
